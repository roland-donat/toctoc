// Visit feedback ("retours", R17 to R20): one entry point shared by the admin entry, the field link (U12)
// and the paper re-entry (U13). Idempotent on the client-generated id (KTD10).
import { desc, eq } from "drizzle-orm"
import { z } from "zod"
import type { AppContext } from "../context.ts"
import type { Db } from "../db/index.ts"
import { addresses, visits } from "../db/schema/index.ts"
import { activeExclusion, parisDate } from "../domain/qualification.ts"

export type Visit = typeof visits.$inferSelect

export type VisitErrorCode =
  | "address_not_found"
  | "no_active_qualification"
  | "visit_not_found"
  /** A cancellation row is the trace of a lifted qualification (R5): it is neither corrected nor deleted. */
  | "cancellation_locked"
  /** A corrected feedback still needs the contact or the qualification, as on entry. */
  | "empty_feedback"

export class VisitError extends Error {
  readonly code: VisitErrorCode
  constructor(code: VisitErrorCode) {
    super(code)
    this.name = "VisitError"
    this.code = code
  }
}

/** ISO calendar date that exists (2027-02-30 is refused). */
export const isoDateSchema = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/)
  .refine((s) => {
    const d = new Date(`${s}T00:00:00Z`)
    return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === s
  })

const optionalText = (max: number) =>
  z
    .string()
    .max(max)
    .nullish()
    .transform((s) => (s === null || s === undefined || s.trim() === "" ? null : s.trim()))

/** Fields of a feedback (R18); never a political opinion. */
export const visitInputSchema = z.object({
  /** Generated by the client, so a resend never duplicates. */
  id: z.string().uuid(),
  addressId: z.string().min(1).max(100),
  source: z.enum(["lien", "feuille", "admin"]),
  /** Defaults to today in Paris (live entry). */
  visitDate: isoDateSchema.optional(),
  itineraryId: z.string().max(100).nullish(),
  dwelling: optionalText(200),
  contact: z.enum(["obtenu", "absent"]).nullish(),
  contactQuality: z.enum(["chaleureux", "poli", "ferme"]).nullish(),
  toAccompany: z.boolean().default(false),
  toRevisit: z.boolean().default(false),
  qualification: z.enum(["non_habitation", "logement_vide", "residence_secondaire"]).nullish(),
  qualificationScope: z.enum(["logement", "immeuble"]).nullish(),
  remarks: optionalText(2000),
})

export type VisitInput = z.input<typeof visitInputSchema>

export interface RecordVisitResult {
  visit: Visit
  /** False when a row with this id already existed: the stored row is returned unchanged. */
  created: boolean
}

function findVisit(db: Db, id: string): Visit | undefined {
  return db.select().from(visits).where(eq(visits.id, id)).get()
}

type VisitRow = typeof visits.$inferInsert

function insertOnce(ctx: AppContext, row: VisitRow): RecordVisitResult {
  const inserted = ctx.db.insert(visits).values(row).onConflictDoNothing({ target: visits.id }).returning().all()
  const created = inserted[0]
  if (created) return { visit: created, created: true }
  const existing = findVisit(ctx.db, row.id)
  if (!existing) throw new Error("visit insert ignored without existing row")
  return { visit: existing, created: false }
}

function assertAddress(db: Db, addressId: string): void {
  const found = db.select({ id: addresses.id }).from(addresses).where(eq(addresses.id, addressId)).get()
  if (!found) throw new VisitError("address_not_found")
}

/** Records a feedback; sending the same id again returns the stored row without creating another. */
export function recordVisit(ctx: AppContext, input: VisitInput): RecordVisitResult {
  const v = visitInputSchema.parse(input)
  const existing = findVisit(ctx.db, v.id)
  if (existing) return { visit: existing, created: false }
  assertAddress(ctx.db, v.addressId)
  const now = ctx.now()
  return insertOnce(ctx, {
    id: v.id,
    addressId: v.addressId,
    dwelling: v.dwelling,
    visitDate: v.visitDate ?? parisDate(now),
    recordedAt: now.getTime(),
    source: v.source,
    itineraryId: v.itineraryId ?? null,
    contact: v.contact ?? null,
    contactQuality: v.contactQuality ?? null,
    toAccompany: v.toAccompany,
    toRevisit: v.toRevisit,
    qualification: v.qualification ?? null,
    qualificationScope: v.qualification ? (v.qualificationScope ?? null) : null,
    remarks: v.remarks,
  })
}

/** Dated history of an address, newest visit first (R9, R20). Cancellations are part of it. */
export function listVisits(db: Db, addressId: string): Visit[] {
  return db
    .select()
    .from(visits)
    .where(eq(visits.addressId, addressId))
    .orderBy(desc(visits.visitDate), desc(visits.recordedAt))
    .all()
}

/**
 * Lifts the qualification that excludes the address (R5), traced as a feedback row of the
 * administrator with qualification "annulation" (U6 step 4).
 */
export function cancelQualification(ctx: AppContext, input: { addressId: string; id?: string }): RecordVisitResult {
  if (input.id) {
    const existing = findVisit(ctx.db, input.id)
    if (existing) return { visit: existing, created: false }
  }
  assertAddress(ctx.db, input.addressId)
  if (activeExclusion(listVisits(ctx.db, input.addressId)) === null) throw new VisitError("no_active_qualification")
  const now = ctx.now()
  return insertOnce(ctx, {
    id: input.id ?? crypto.randomUUID(),
    addressId: input.addressId,
    dwelling: null,
    visitDate: parisDate(now),
    recordedAt: now.getTime(),
    source: "admin",
    itineraryId: null,
    toAccompany: false,
    toRevisit: false,
    qualification: "annulation",
    qualificationScope: "immeuble",
    remarks: null,
  })
}

/** Free text of a correction: absent leaves the stored value, empty clears it. */
const patchText = (max: number) =>
  z
    .string()
    .max(max)
    .nullable()
    .optional()
    .transform((s) => (s === undefined ? undefined : s === null || s.trim() === "" ? null : s.trim()))

/**
 * Correction of a feedback, by the administrator or from the field link that sent it: only the fields sent change. The free texts may be hidden
 * (anonymous mode), so a client that did not show them leaves them out instead of sending them empty.
 */
export const visitPatchSchema = z
  .object({
    dwelling: patchText(200),
    contact: z.enum(["obtenu", "absent"]).nullable().optional(),
    contactQuality: z.enum(["chaleureux", "poli", "ferme"]).nullable().optional(),
    toAccompany: z.boolean().optional(),
    toRevisit: z.boolean().optional(),
    qualification: z.enum(["non_habitation", "logement_vide", "residence_secondaire"]).nullable().optional(),
    qualificationScope: z.enum(["logement", "immeuble"]).nullable().optional(),
    remarks: patchText(2000),
  })
  .strict()

export type VisitPatch = z.input<typeof visitPatchSchema>

function editableVisit(db: Db, id: string): Visit {
  const visit = findVisit(db, id)
  if (!visit) throw new VisitError("visit_not_found")
  if (visit.qualification === "annulation") throw new VisitError("cancellation_locked")
  return visit
}

/** Corrects a feedback in place and dates the correction (callers check who may correct it); the visit date, source and itinerary stay. */
export function updateVisit(ctx: AppContext, id: string, input: VisitPatch): Visit {
  const patch = visitPatchSchema.parse(input)
  const visit = editableVisit(ctx.db, id)
  const defined = Object.fromEntries(Object.entries(patch).filter(([, v]) => v !== undefined)) as Partial<Visit>
  const merged = { ...visit, ...defined }
  if (merged.contact === null && merged.qualification === null) throw new VisitError("empty_feedback")
  const updated = ctx.db
    .update(visits)
    .set({
      dwelling: merged.dwelling,
      contact: merged.contact,
      // Same coherence as on entry: a quality only with a contact, a scope only with a qualification.
      contactQuality: merged.contact === "obtenu" ? merged.contactQuality : null,
      toAccompany: merged.toAccompany,
      toRevisit: merged.toRevisit,
      qualification: merged.qualification,
      qualificationScope: merged.qualification ? merged.qualificationScope : null,
      remarks: merged.remarks,
      correctedAt: ctx.now().getTime(),
    })
    .where(eq(visits.id, id))
    .returning()
    .all()[0]
  if (!updated) throw new VisitError("visit_not_found")
  return updated
}

/** Removes a feedback entered by mistake: the door gets back the follow-up state its other feedbacks give it. */
export function deleteVisit(ctx: AppContext, id: string): Visit {
  const visit = editableVisit(ctx.db, id)
  ctx.db.delete(visits).where(eq(visits.id, id)).run()
  return visit
}

/** Feedbacks recorded through one itinerary (field link and paper sheet), oldest entry first. */
export function listItineraryVisits(db: Db, itineraryId: string): Visit[] {
  return db.select().from(visits).where(eq(visits.itineraryId, itineraryId)).orderBy(visits.recordedAt).all()
}
